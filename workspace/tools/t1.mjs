import { chromium } from 'playwright'
const OUT = '../04-logs/home-demo/'
const b = await chromium.launch(); const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true }); const p = await c.newPage()
const errs = []; p.on('console', m => m.type() === 'error' && errs.push(m.text())); p.on('pageerror', e => errs.push(String(e)))
await p.goto('http://localhost:4321/', { waitUntil: 'networkidle' })
await p.screenshot({ path: OUT + 'T1-a-top.png' })
const barState = async () => p.evaluate(() => document.getElementById('sticky-bar').dataset.visible)
console.log('bar at top:', await barState())
await p.click('#menu-btn'); await p.waitForTimeout(200); await p.screenshot({ path: OUT + 'T1-b-menu.png' })
console.log('menu expanded:', await p.getAttribute('#menu-btn', 'aria-expanded'))
await p.keyboard.press('Escape'); console.log('after Esc expanded:', await p.getAttribute('#menu-btn', 'aria-expanded'))
await p.evaluate(() => window.scrollTo(0, 450)); await p.waitForTimeout(500)
console.log('bar mid-scroll:', await barState()); await p.screenshot({ path: OUT + 'T1-c-scrolled.png' })
await p.evaluate(() => document.getElementById('request').scrollIntoView()); await p.waitForTimeout(500)
console.log('bar at request:', await barState())
const small = await p.evaluate(() => [...document.querySelectorAll('a,button')].filter(e => e.offsetParent !== null || e.id === 'menu-btn').map(e => { const r = e.getBoundingClientRect(); return { t: (e.textContent || e.getAttribute('aria-label') || '').trim().slice(0, 20), w: Math.round(r.width), h: Math.round(r.height) } }).filter(x => x.h < 44 || x.w < 44))
console.log('targets under 44px:', JSON.stringify(small))
const overflow = await p.evaluate(() => document.documentElement.scrollWidth > innerWidth); console.log('horizontal overflow:', overflow)
console.log('console errors:', errs.length, errs.slice(0, 3))
await b.close()
